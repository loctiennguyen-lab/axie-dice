/* §3.1 baseName: strip trailing α / + then trim + collapse inner double spaces */
function baseName(x) {
  let s = String(x == null ? '' : x);
  for (;;) {
    const t = s.replace(/[\s]*[α+]\s*$/u, '');
    if (t === s) break;
    s = t;
  }
  return s.trim().replace(/\s{2,}/g, ' ');
}
