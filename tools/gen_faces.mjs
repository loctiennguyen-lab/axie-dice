/* Runtime bundle carrier (ADR: generated data reaches the game as a src/ module).
 *
 * build.py concatenates ONLY the files in its FILES list and never reads assets/; the game
 * ships as one self-contained HTML with no bundler and no runtime fetch. So the JSON snapshot
 * — which stays the reviewable artefact and the thing --check diffs — is ALSO emitted as
 * src/part_faces.js declaring a plain `const`, exactly the way src/art.js already carries
 * generated sprite data. Both files are written from the same object in the same run, and
 * --check byte-compares both, so a stale bundle is a RED gate, never a silent ship. */
function buildRuntimeJs(out) {
  return '/* GENERATED by tools/gen_faces.mjs — DO NOT EDIT BY HAND.\n'
    + '   Source of truth: assets/data/part_faces.json (same bytes, same run).\n'
    + '   Re-generate with: node tools/gen_faces.mjs   ·   verify with: node tools/gen_faces.mjs --check\n'
    + '   design/gdd/part-skill-identity.md §6f. Consumed by axieToDie() in src/engine.js. */\n'
    + 'const PART_FACES = ' + JSON.stringify(out) + ';\n';
}

function buildOutput(rep, engineVersion) {
  const familyVariant = {};
  for (const [id, rec] of [...rep.variantValues.entries()].sort()) {
    const { cls, slot, letter, t, k } = rec.tpl;
    familyVariant[cls] = familyVariant[cls] || {};
    familyVariant[cls][slot] = familyVariant[cls][slot] || {};
    /* `v` is the pinned value at gene 0 / coherence 1 — what reviewers read in the diff.
       `m`/`c`/`mode` let engine.js re-derive it at any other budget (gene ladder §3.4a,
       coherence §3.4b); `lift` carries the F6 monotone bump and any REPAIR bump, which are
       per-BUCKET decisions the affine model cannot know about. By construction,
       max(1, ROUND(m*B_base - c)) + lift[b] === v[b] — asserted by I28 below. */
    const B = (b) => rep.constants.B_C * rep.constants.S[b];
    const evalAff = (aff, budget) => {
      const x = aff.m * budget - aff.c;
      return Math.max(1, aff.mode === 'f' ? Math.floor(x) : Math.round(x));
    };
    const lift = {};
    for (const b of ['C', 'O', 'P']) {
      lift[b] = rec.v[b] - evalAff(rec.aff, B(b));
      if (!Number.isFinite(lift[b])) hardFail('I28', `${id}@${b}`, 'a finite monotone/repair lift', String(lift[b]));
    }
    familyVariant[cls][slot][letter] = {
      t, k, v: { C: rec.v.C, O: rec.v.O, P: rec.v.P },
      m: rec.aff.m, c: rec.aff.c, mode: rec.aff.mode, lift,
      ...(rec.sup ? { sup: { k: rec.sup.k, m: rec.sup.aff.m, c: rec.sup.aff.c, mode: rec.sup.aff.mode } } : {}),
    };
  }
  const signatureFace = {};
  for (const f of rep.sigFaces) signatureFace[f.key] = { p: f.p, t: f.t, v: f.v, k: f.k, r: f.r, src: 'sig' };
  const partVariant = {};
  for (const a of [...rep.pv.map.values()].sort((x, y) => (x.key < y.key ? -1 : 1))) partVariant[a.key] = a.letter;
  const scarcityBucket = {};
  for (const i of rep.identities) scarcityBucket[i.key] = i.bucket;
  return {
    schema: 1,
    engineVersion,
    profile: rep.profile,
    constants: rep.constants,
    familyVariant, signatureFace, partVariant, scarcityBucket,
    manifest: {
      monotoneLifts: rep.monotoneLifts,
      sigLifts: rep.sigLifts,
      spreadLog: rep.spreadLog,
      suppressLog: rep.suppressLog,
      repairLog: rep.repair.repairLog,
      clampFloor: rep.clampFloor,
      totals: {
        nSig: rep.counts.signatures, nC: rep.counts.nC, nO: rep.counts.nO,
        nP: rep.counts.nP, nX: rep.counts.nX, variants: rep.counts.variants,
        spares: rep.counts.spares, spareList: rep.counts.spareList,
        designedFaces: rep.counts.designedFaces, reachableFaces: rep.counts.reachableFaces,
        distinctEngineFaces: rep.counts.distinctEngineFaces,
        distinctIdentityFaces: rep.counts.distinctIdentity,
        perSlot: Object.fromEntries(SLOT_ORDER.map((s) => [s, {
          parts: rep.counts.perSlot[s].parts,
          distinct: rep.counts.perSlot[s].distinct,
          lost: rep.counts.perSlot[s].lost,
        }])),
      },
    },
  };
}

/* engineVersion — read from src/engine.js via the house vm loader (§6f "khớp src/engine.js:9") */
function readEngineVersion() {
  try {
    const ctx = { console, Math, JSON };
    vm.createContext(ctx);
    const src = ['src/data.js', 'src/engine.js'].map((f) => fs.readFileSync(P(f), 'utf8')).join('\n')
      + '\n;globalThis.__X={VERSION: (typeof VERSION!=="undefined"?VERSION:null)};';
    vm.runInContext(src, ctx);
    if (ctx.__X && ctx.__X.VERSION) return String(ctx.__X.VERSION);
  } catch { /* fall through */ }
  const m = /(?:VERSION|BUILD)\s*=\s*['"]([^'"]+)['"]/.exec(fs.readFileSync(P('src/engine.js'), 'utf8'));
  return m ? m[1] : 'unknown';
}

/* AC-33 — --check-citations */
function checkCitations(md) {
  const out = [];
  const re = /`?(src\/[a-z_]+\.js|api\/[a-z-]+\.js):(\d+)(?:-\d+)?`?/g;
  const cache = new Map();
  const readLines = (f) => {
    if (!cache.has(f)) cache.set(f, fs.existsSync(P(f)) ? fs.readFileSync(P(f), 'utf8').split('\n') : null);
    return cache.get(f);
  };
  const lines = md.split('\n');
  for (let i = 0; i < lines.length; i++) {
    for (const m of lines[i].matchAll(re)) {
      const [, file, numS] = m;
      const num = Number(numS);
      const src = readLines(file);
      if (!src) { out.push({ doc: i + 1, file, num, status: 'FILE-MISSING' }); continue; }
      /* find a symbol name mentioned next to the citation */
      const around = lines[i];
      const symMatch = [...around.matchAll(/`([A-Za-z_$][A-Za-z0-9_$]*)`/g)].map((x) => x[1])
        .filter((s) => s !== 'src' && !/\.js$/.test(s));
      let ok = null, found = [];
      for (const sym of symMatch) {
        const hits = [];
        for (let j = 0; j < src.length; j++) {
          if (new RegExp(`(^|[^A-Za-z0-9_$])${sym.replace(/[$]/g, '\\$')}\\s*[=:(]`).test(src[j])) hits.push(j + 1);
        }
        if (!hits.length) continue;
        found.push({ sym, hits });
        if (hits.some((h) => Math.abs(h - num) <= 3)) { ok = sym; break; }
      }
      if (symMatch.length && ok === null && found.length) {
        out.push({ doc: i + 1, file, num, status: 'DRIFT', candidates: found.slice(0, 3) });
      }
    }
  }
  return out;
}

