const IC_CACHE={};
function icoSvg(name,col){
  const g=IC_G[name]; if(!g) return '';
  const key=name+'|'+(col||'');
  if(IC_CACHE[key]) return IC_CACHE[key];
  const c=col||IC_COL[name]||'#fff';
  let r='';
  for(let y=0;y<g.length;y++){
    let x=0; const row=g[y];
    while(x<row.length){
      if(row[x]==='#'){ let w=0; while(x+w<row.length&&row[x+w]==='#')w++;
        r+=`<rect x="${x}" y="${y}" width="${w}" height="1"/>`; x+=w; }
      else x++;
    }
  }
  const out=`<svg class="ico" viewBox="0 0 8 8" fill="${c}" shape-rendering="crispEdges" xmlns="http://www.w3.org/2000/svg">${r}</svg>`;
  IC_CACHE[key]=out; return out;
}
function ico(name,cls,col){
  const s=el('span','icow '+(cls||'')); s.innerHTML=icoSvg(name,col); return s;
}
